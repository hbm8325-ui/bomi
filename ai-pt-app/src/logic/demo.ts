function genericDemo(scenario: Scenario): DemoSet {
  const first = scenario.resources[0]
  const second = scenario.resources[1]
  const difficulty = scenario.difficulty ? ` · ${scenario.difficulty}` : ''
  return {
    broad: `이 과제는 ${scenario.field} 분야의 의사결정 문제입니다${difficulty}. 일반적인 접근은 ① 현황과 결정해야 할 것 정리 ② 원인·쟁점 분석 ③ 대안 비교(비용·일정·부작용) ④ 실행계획과 확인 지표 순서입니다. 어느 단계를 먼저 볼지, 어떤 제약(일정·예산·인력)이 중요한지 알려주시면 그 기준으로 더 좁혀 분석해 드리겠습니다.`,
    topics: [],
    fallback: `${first?.label ?? '자료 1'}(${first?.title ?? ''})과 ${second?.label ?? '자료 2'}(${second?.title ?? ''})를 확인했습니다. 여기에는 해당 내부 기록이 따로 없으니, 일반 기준으로는 정리할 수 있지만 자료에 있는 조건에 맞춘 답을 원하시면 어느 표의 어떤 항목을 볼지 지정해 주세요. 예: "자료 1의 표를 항목별로 정리", "자료 2의 대안을 비용·기간으로 비교".`,
  }
}

export function demoSetFor(scenario: Scenario): DemoSet {
  return DEMO[scenario.id] ?? genericDemo(scenario)
}

/** 데모 응답 생성: 넓은 질문에는 원론, 좁은 질문에는 자료 기반 정확 응답 */
export function demoReply(scenario: Scenario, question: string): string {
  const set = demoSetFor(scenario)
  const verdict = classifyPrompt(question)
  if (verdict.kind === 'broad') return set.broad
  const hit = set.topics.find(topic => topic.match.test(question))
  if (hit) return hit.answer
  if (verdict.kind === 'targeted') return set.fallback
  return set.fallback
}

/** 데모 리허설 피드백 (키 없이도 동작) */
export function demoRehearsalFeedback(_question: string, defense: string): string[] {
  const text = defense.trim()
  const chars = Array.from(text).length
  const hasNumber = /\d/.test(text)
  const hasResource = /자료|표|측정|기준|ppm|억|%/.test(text)
  const hasBecause = /왜냐하면|때문|근거|이유/.test(text)
  const hasRisk = /리스크|한계|다만|보완|잔여|우려/.test(text)

  const line1 =
    chars < 20
      ? '결론 먼저: 답이 너무 짧아 첫 문장이 결론인지 판단하기 어렵습니다. "결론적으로 ~합니다"로 시작해 15초 안에 답을 끝내세요.'
      : /^(결론|따라서|저는|제 판단|우선)/.test(text) || text.indexOf('다.') < 60
        ? '결론 먼저: 첫 문장에 판단을 둔 점은 좋습니다. 다만 질문에 대한 답을 한 문장으로 더 압축하세요.'
        : '결론 먼저: 배경 설명이 먼저 나옵니다. 첫 문장을 "결론적으로 ○○하겠습니다"로 바꿔야 면접관이 답을 놓치지 않습니다.'

  const line2 = hasResource && hasNumber
    ? '자료 근거: 수치를 붙인 점은 좋습니다. 어느 자료의 몇 번째 표인지까지 말하면 신뢰도가 올라갑니다.'
    : hasResource
      ? '자료 근거: 자료를 언급했지만 수치가 없습니다. "제어풍속 0.32 m/s(기준 0.5)"처럼 숫자를 하나 넣으세요.'
      : '자료 근거: 자료 근거가 보이지 않습니다. 참고자료의 표·수치를 최소 하나 인용해야 방어가 됩니다.'

  const line3 = hasRisk
    ? '놓친 리스크: 반론을 일부 다뤘습니다. 그 리스크가 현실화할 조건(일정·비용)을 한 줄 더 붙이세요.'
    : hasBecause
      ? '놓친 리스크: 이유는 말했지만 반대 논리를 막지 못했습니다. "다만 ~ 경우에는 ~로 전환" 같은 조건부 문장을 넣으세요.'
      : '놓친 리스크: 반론 대비가 없습니다. 면접관은 "그럼 비용은요?"를 반드시 묻습니다. 대가를 먼저 말하세요.'

  return [line1, line2, line3]
}

